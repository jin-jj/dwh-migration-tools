package com.google.edwmigration.dumper.application.dumper.connector.databricks;

import static com.google.edwmigration.dumper.application.dumper.connector.databricks.DatabricksHiveMetastoreDdlParser.parseColumnClauses;
import static org.junit.Assert.assertEquals;

import com.google.common.collect.ImmutableList;
import com.google.common.collect.ImmutableMap;
import com.google.edwmigration.dumper.application.dumper.connector.databricks.DatabricksHiveMetastoreDdlParser.ParsedColumnClauses;
import java.util.Map;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.junit.runners.JUnit4;

@RunWith(JUnit4.class)
public class DatabricksHiveMetastoreDdlParserTest {

  @Test
  public void parseColumnClauses_parsesGeneratedAndIdentityColumnsAsDatabricksPrintsThem() {
    String ddl =
        String.join(
            "\n",
            "CREATE TABLE hive_metastore.sales.orders (",
            "  row_id BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),",
            "  base_price DECIMAL(10,2) NOT NULL,",
            "  tax_pct DECIMAL(4,2) NOT NULL,",
            "  total DECIMAL(10,2) GENERATED ALWAYS AS ("
                + " CAST(base_price * (1.0 + tax_pct / 100.0) AS DECIMAL(10, 2)) ),",
            "  created_at TIMESTAMP,",
            "  created_date DATE GENERATED ALWAYS AS ( CAST(created_at AS DATE) ))",
            "USING delta",
            "TBLPROPERTIES (",
            "  'delta.feature.generatedColumns' = 'supported',",
            "  'delta.feature.identityColumns' = 'supported')");

    assertEquals(
        ImmutableMap.of(
            "row_id", "||ALWAYS|1|1",
            "total", "|CAST(base_price * (1.0 + tax_pct / 100.0) AS DECIMAL(10, 2))|||",
            "created_date", "|CAST(created_at AS DATE)|||"),
        describe(parseColumnClauses(ddl)));
  }

  @Test
  public void parseColumnClauses_parsesIdentityOptions() {
    String ddl =
        String.join(
            "\n",
            "CREATE TABLE hive_metastore.sales.ids (",
            "  by_default BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 10),",
            "  descending BIGINT GENERATED ALWAYS AS IDENTITY (START WITH -1 INCREMENT BY -2),",
            "  plain BIGINT GENERATED ALWAYS AS IDENTITY)",
            "USING delta");

    assertEquals(
        ImmutableMap.of(
            "by_default", "||BY DEFAULT|100|10",
            "descending", "||ALWAYS|-1|-2",
            "plain", "||ALWAYS||"),
        describe(parseColumnClauses(ddl)));
  }

  @Test
  public void parseColumnClauses_keysColumnsByLowerCaseUnquotedName() {
    String ddl =
        String.join(
            "\n",
            "CREATE TABLE hive_metastore.sales.`odd (name)` (",
            "  `Event Day` DATE GENERATED ALWAYS AS ( CAST(ts AS DATE) ),",
            "  `back``tick` INT GENERATED ALWAYS AS ( 1 ),",
            "  Upper BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1))",
            "USING delta");

    assertEquals(
        ImmutableList.of("event day", "back`tick", "upper"),
        ImmutableList.copyOf(parseColumnClauses(ddl).keySet()));
  }

  @Test
  public void parseColumnClauses_ignoresClauseTextInLiteralsTypesAndFunctionNames() {
    String ddl =
        String.join(
            "\n",
            "CREATE TABLE hive_metastore.sales.tricky (",
            "  note STRING COMMENT 'GENERATED ALWAYS AS (x), not a clause\\'s text,\nreally',",
            "  payload STRUCT<generated: INT, b: STRING> COMMENT 'struct, with commas',",
            "  flag BOOLEAN DEFAULT 1 < 2,",
            "  label STRING DEFAULT generated('x'),",
            "  doubled INT GENERATED ALWAYS AS ( id * 2 ))",
            "USING delta");

    assertEquals(ImmutableMap.of("doubled", "|id * 2|||"), describe(parseColumnClauses(ddl)));
  }

  @Test
  public void parseColumnClauses_splitsColumnsOutsideTypeBrackets() {
    String ddl =
        String.join(
            "\n",
            "CREATE TABLE hive_metastore.sales.points (",
            "  id INT,",
            "  point STRUCT<x: INT, y: INT> GENERATED ALWAYS AS ( named_struct('x', id, 'y', 0) ),",
            "  tags MAP<STRING, ARRAY<INT>>)",
            "USING delta");

    assertEquals(
        ImmutableMap.of("point", "|named_struct('x', id, 'y', 0)|||"),
        describe(parseColumnClauses(ddl)));
  }

  @Test
  public void parseColumnClauses_keepsLiteralsAndParenthesesInExpressions() {
    String ddl =
        "create external table hive_metastore.sales.texts (\n"
            + "  code STRING generated always as ( concat('(', id, ')', \"x)\") ))\n"
            + "using delta";

    assertEquals(
        ImmutableMap.of("code", "|concat('(', id, ')', \"x)\")|||"),
        describe(parseColumnClauses(ddl)));
  }

  @Test
  public void parseColumnClauses_returnsNoClausesWithoutColumnList() {
    for (String ddl :
        ImmutableList.of(
            "CREATE VIEW hive_metastore.sales.v (\n  id GENERATED)\nAS SELECT 1 AS id",
            "CREATE TABLE hive_metastore.sales.t\nUSING delta\nLOCATION 'dbfs:/t'",
            "CREATE TABLE hive_metastore.sales.cut (\n  id BIGINT GENERATED ALWAYS AS IDENTITY",
            "")) {
      assertEquals(ddl, ImmutableMap.of(), parseColumnClauses(ddl));
    }
  }

  /**
   * Returns each column as {@code |generationExpression|identityGeneration|start|increment}, by
   * name.
   */
  private static ImmutableMap<String, String> describe(Map<String, ParsedColumnClauses> clauses) {
    ImmutableMap.Builder<String, String> described = ImmutableMap.builder();
    for (Map.Entry<String, ParsedColumnClauses> column : clauses.entrySet()) {
      ParsedColumnClauses value = column.getValue();
      described.put(
          column.getKey(),
          String.join(
              "|",
              "",
              value.generationExpression,
              value.identityGeneration,
              value.identityStart,
              value.identityIncrement));
    }
    return described.build();
  }
}
